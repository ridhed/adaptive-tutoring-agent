import argparse
import json
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.dont_write_bytecode = True
sys.path.insert(0, str(ROOT / "V0" / "Code"))
sys.path.insert(0, str(ROOT / "V1"))
from V0_agent import AgentV0  # noqa: E402
from V1_bkt_agent import BayesianTutoringAgent  # noqa: E402

ACTIONS = ["ANSWER", "ASK", "HINT", "TEACH_PRIOR"]
USE_COLS = ["kc_id", "correct", "mastery_pre", "prior_errors", "policy_action",
            "response_time_seconds", "attempt_count"]


def prepare_cases(input_path: Path, case_count: int, seed: int) -> pd.DataFrame:
    df = pd.read_csv(input_path, usecols=USE_COLS)
    missing_actions = set(ACTIONS) - set(df["policy_action"].dropna().unique())
    if missing_actions:
        raise ValueError(f"Dataset is missing reference actions: {sorted(missing_actions)}")

    # Match V0's preprocessing convention: missing latency is 15 sec; expected
    # latency is the per-skill median, with a 2 sec minimum; FAST is below 30%.
    df["response_seconds"] = pd.to_numeric(df["response_time_seconds"], errors="coerce").fillna(15.0)
    expected = df.groupby("kc_id")["response_seconds"].transform("median").fillna(25.0).clip(lower=2.0)
    df["v0_response_time"] = (df["response_seconds"] < expected * 0.3).map({True: "FAST", False: "SLOW"})
    df["v0_attempt_number"] = pd.to_numeric(df["attempt_count"], errors="coerce").fillna(1).astype(int)
    df["correct"] = pd.to_numeric(df["correct"], errors="raise").astype(int)
    df["mastery_pre"] = pd.to_numeric(df["mastery_pre"], errors="raise")
    df["prior_errors"] = pd.to_numeric(df["prior_errors"], errors="coerce").fillna(0).astype(int)

    base, remainder = divmod(case_count, len(ACTIONS))
    parts = []
    for index, action in enumerate(ACTIONS):
        need = base + (1 if index < remainder else 0)
        pool = df[df["policy_action"] == action]
        if len(pool) < need:
            raise ValueError(f"Need {need} cases for {action}, but dataset has {len(pool)}")
        parts.append(pool.sample(n=need, random_state=seed + index))
    return pd.concat(parts).sample(frac=1, random_state=seed).reset_index(drop=True)


def reference_reason(row) -> str:
    if row.policy_action == "TEACH_PRIOR":
        return "Pre-action mastery below 0.40."
    if row.policy_action == "HINT":
        return "Pre-action mastery from 0.40 to below 0.85."
    if row.policy_action == "ASK":
        return "Mastery at least 0.85 with at least two errors in the previous three responses."
    return "Mastery at least 0.85 without two recent prior errors."


def compare(cases: pd.DataFrame) -> tuple[pd.DataFrame, dict]:
    v0 = AgentV0()
    v1 = BayesianTutoringAgent()
    results = []
    for number, row in enumerate(cases.itertuples(index=False), start=1):
        v0_state, v0_action = v0.predict(
            is_correct=bool(row.correct),
            attempt_number=int(row.v0_attempt_number),
            response_time=str(row.v0_response_time),
        )
        v1_result = v1.select_action(
            p_know=float(row.mastery_pre),
            is_correct=bool(row.correct),
            response_time_sec=float(row.response_seconds),
            prior_errors=[1] * min(int(row.prior_errors), 3),
        )
        reference = str(row.policy_action)
        results.append({
            "case_id": f"TC{number:02d}",
            "skill_id": str(row.kc_id),
            "correct": int(row.correct),
            "attempt_number": int(row.v0_attempt_number),
            "response_time_category": str(row.v0_response_time),
            "mastery_pre": f"{float(row.mastery_pre):.8f}",
            "prior_errors_last_3": int(row.prior_errors),
            "reference_action": reference,
            "reference_reason": reference_reason(row),
            "v0_state": v0_state,
            "v0_action": v0_action,
            "v0_matches_reference": v0_action == reference,
            "v1_state": v1_result["inferred_state"],
            "v1_action": v1_result["prescribed_action"],
            "v1_matches_reference": v1_result["prescribed_action"] == reference,
            "agents_agree": v0_action == v1_result["prescribed_action"],
        })
    result_df = pd.DataFrame(results)
    summary = {
        "case_count": len(result_df),
        "sampling": "Seeded, stratified sample by generated policy_action; no student identifiers exported.",
        "seed": int(cases.attrs.get("seed", 42)),
        "reference_label_note": "policy_action is generated by build_dataset.py; agreement is not independent ground truth.",
        "v0_matches_reference": int(result_df["v0_matches_reference"].sum()),
        "v0_reference_agreement_rate": float(result_df["v0_matches_reference"].mean()),
        "v1_matches_reference": int(result_df["v1_matches_reference"].sum()),
        "v1_reference_agreement_rate": float(result_df["v1_matches_reference"].mean()),
        "agents_agree": int(result_df["agents_agree"].sum()),
        "agent_agreement_rate": float(result_df["agents_agree"].mean()),
        "action_distribution": {a: int((result_df["reference_action"] == a).sum()) for a in ACTIONS},
        "v0_disagreements_by_reference": {},
        "v1_disagreements_by_reference": {},
    }
    for agent, field in [("v0", "v0_matches_reference"), ("v1", "v1_matches_reference")]:
        summary[f"{agent}_disagreements_by_reference"] = {
            action: int(((result_df["reference_action"] == action) & ~result_df[field]).sum())
            for action in ACTIONS
        }
    return result_df, summary


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, default=ROOT / "dataset" / "ground_truth.csv")
    parser.add_argument("--case-count", type=int, default=40, help="Choose 30-50 cases (default: 40).")
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--output", type=Path, default=ROOT / "analysis" / "v0_v1_case_comparison.csv")
    parser.add_argument("--summary", type=Path, default=ROOT / "analysis" / "v0_v1_case_summary.json")
    args = parser.parse_args()
    if not 30 <= args.case_count <= 50:
        parser.error("--case-count must be between 30 and 50")

    cases = prepare_cases(args.input, args.case_count, args.seed)
    cases.attrs["seed"] = args.seed
    result, summary = compare(cases)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.summary.parent.mkdir(parents=True, exist_ok=True)
    result.to_csv(args.output, index=False)
    args.summary.write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(summary, indent=2))
    print(f"\nWrote {len(result)} cases to {args.output}")
    print(f"Wrote summary to {args.summary}")


if __name__ == "__main__":
    main()